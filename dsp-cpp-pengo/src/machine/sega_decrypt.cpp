void decrypt_sega(uint8_t* data, uint8_t* opcodes, int game, size_t length) {
    if (game < 0 || game > 8) return;
    if (length > 0x8000) length = 0x8000;
    for (size_t address = 0; address < length; address++) {
        uint8_t src = data[address];
        uint8_t xorr = 0;
        // pick the translation table from bits 0, 4, 8 and 12 of the address
        int row = int(address & 1) + (int((address >> 4) & 1) << 1) +
                  (int((address >> 8) & 1) << 2) + (int((address >> 12) & 1) << 3);
        // pick the offset in the table from bits 3 and 5 of the source data
        int col = int((src >> 3) & 1) + (int((src >> 5) & 1) << 1);
        // the bottom half of the translation table is the mirror image of the top
        if (src & 0x80) {
            col = 3 - col;
            xorr = 0xa8;
        }
        opcodes[address] = uint8_t((src & ~0xa8) | (kConvTable[game][2 * row][col] ^ xorr));
        data[address] = uint8_t((src & ~0xa8) | (kConvTable[game][2 * row + 1][col] ^ xorr));
    }
}

